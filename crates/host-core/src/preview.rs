/// One error the probe saw.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ProbeEntry {
    /// The component (`path#Export`) or the request URL.
    pub source: String,
    pub message: String,
    pub stack: String,
}

/// The probe's report, once validated.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ProbeReport {
    pub schema: u16,
    pub nonce: String,
    /// Components that mounted (`path#Export`).
    pub rendered: Vec<String>,
    pub console_errors: Vec<ProbeEntry>,
    pub uncaught_exceptions: Vec<ProbeEntry>,
    pub failed_requests: Vec<ProbeEntry>,
    pub tauri_visible: bool,
    pub top_is_self: bool,
    pub a11y: String,
    pub html: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum ProbeError {
    #[error("the preview report exceeds {MAX_REPORT_BYTES} bytes")]
    TooLarge,
    #[error("the preview report is malformed: {0}")]
    Malformed(String),
    #[error("the preview report is for another run")]
    WrongNonce,
    #[error("unsupported preview report schema {0}")]
    WrongSchema(u16),
    #[error("the preview report exceeds its bounds")]
    OutOfBounds,
}

/// Parses the harness's report. Anything unexpected is refused, never repaired.
pub fn parse_probe_report(bytes: &[u8], nonce: &str) -> Result<ProbeReport, ProbeError> {
    if bytes.len() > MAX_REPORT_BYTES {
        return Err(ProbeError::TooLarge);
    }
    let report: ProbeReport =
        serde_json::from_slice(bytes).map_err(|error| ProbeError::Malformed(error.to_string()))?;
    if report.schema != SCHEMA {
        return Err(ProbeError::WrongSchema(report.schema));
    }
    if nonce.is_empty() || report.nonce != nonce {
        return Err(ProbeError::WrongNonce);
    }
    let entries = [
        &report.console_errors,
        &report.uncaught_exceptions,
        &report.failed_requests,
    ];
    let bounded = report.rendered.len() <= 4 * MAX_ENTRIES
        && report.rendered.iter().all(|name| name.len() <= MAX_TEXT)
        && entries.iter().all(|list| {
            list.len() <= MAX_ENTRIES
                && list.iter().all(|entry| {
                    entry.source.len() <= MAX_TEXT
                        && entry.message.len() <= MAX_TEXT
                        && entry.stack.len() <= 2 * MAX_TEXT
                })
        })
        && report.html.len() <= MAX_HTML
        && report.a11y.len() <= MAX_A11Y;
    if !bounded {
        return Err(ProbeError::OutOfBounds);
    }
    Ok(report)
}

impl ProbeReport {
    /// The Tauri bridge was reachable or the page was framed by another document.
    #[must_use]
    pub fn isolation_breached(&self) -> bool {
        self.tauri_visible || !self.top_is_self
    }

    /// Whether the components mounted without an error the Judge rejects. Failed requests are
    /// reported but do not fail: the preview has no network by design.
    #[must_use]
    pub fn passed(&self) -> bool {
        self.console_errors.is_empty()
            && self.uncaught_exceptions.is_empty()
            && !self.isolation_breached()
    }

    /// The `Evidence` part of this report.
    #[must_use]
    pub fn runtime_report(&self) -> PreviewRuntimeReport {
        PreviewRuntimeReport {
            inspected_url: preview_url(&self.rendered),
            console_error_count: self.console_errors.len() as u32,
            uncaught_exception_count: self.uncaught_exceptions.len() as u32,
            failed_network_request_count: self.failed_requests.len() as u32,
            crashed: self.isolation_breached(),
            dom_snapshot_hash: Some(
                blake3::hash(format!("{}\0{}", self.a11y, self.html).as_bytes())
                    .to_hex()
                    .to_string(),
            ),
        }
    }

    /// One diagnostic per error, with its stack trace, for the agent and the review.
    #[must_use]
    pub fn diagnostics(&self) -> Vec<DiagnosticEntry> {
        let mut items = Vec::new();
        if self.tauri_visible {
            items.push(diagnostic(
                "",
                DiagnosticSeverity::Error,
                "preview-isolation",
                "The Tauri bridge was visible to the previewed component.".into(),
            ));
        }
        if !self.top_is_self {
            items.push(diagnostic(
                "",
                DiagnosticSeverity::Error,
                "preview-isolation",
                "The previewed component was framed by another document.".into(),
            ));
        }
        let entries = [
            (
                &self.uncaught_exceptions,
                DiagnosticSeverity::Error,
                "uncaught-exception",
            ),
            (
                &self.console_errors,
                DiagnosticSeverity::Error,
                "console-error",
            ),
            (
                &self.failed_requests,
                DiagnosticSeverity::Information,
                "failed-request",
            ),
        ];
        for (list, severity, code) in entries {
            for entry in list {
                let message = if entry.stack.is_empty() {
                    format!("{}: {}", entry.source, entry.message)
                } else {
                    format!("{}: {}\n{}", entry.source, entry.message, entry.stack)
                };
                items.push(diagnostic(file_of(&entry.source), severity, code, message));
            }
        }
        items
    }
}

/// A preview that produced no report: the watchdog stopped it, or the harness crashed.
#[must_use]
pub fn crashed_report(
    components: &[String],
    reason: &str,
) -> (PreviewRuntimeReport, DiagnosticEntry) {
    (
        PreviewRuntimeReport {
            inspected_url: preview_url(components),
            console_error_count: 0,
            uncaught_exception_count: 0,
            failed_network_request_count: 0,
            crashed: true,
            dom_snapshot_hash: None,
        },
        diagnostic(
            components.first().map_or("", String::as_str),
            DiagnosticSeverity::Error,
            "preview-crashed",
            reason.to_string(),
        ),
    )
}

/// The static document the IDE shows: the rendered DOM under a policy that runs nothing and
/// loads nothing. It goes in an iframe with `sandbox=""` (opaque origin, no script).
#[must_use]
pub fn snapshot_document(html: &str) -> String {
    format!(
        "<!doctype html><html><head><meta charset=\"utf-8\"><meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'; img-src data:\"></head><body>{html}</body></html>"
    )
}

fn preview_url(rendered: &[String]) -> String {
    let mut url = String::from("hilo-preview:");
    url.push_str(&rendered.join(","));
    url.chars().take(MAX_TEXT).collect()
}

fn file_of(source: &str) -> &str {
    source.split('#').next().unwrap_or(source)
}

fn diagnostic(
    file: &str,
    severity: DiagnosticSeverity,
    code: &str,
    message: String,
) -> DiagnosticEntry {
    DiagnosticEntry {
        file_path: file.to_string(),
        span_utf16: Utf16Span::default(),
        line_col: LineCol::default(),
        source: DiagnosticSource::PreviewRuntime,
        severity,
        code: code.to_string(),
        message,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn report(nonce: &str) -> String {
        format!(
            r#"{{"schema":1,"nonce":"{nonce}","rendered":["src/A.tsx#A"],"console_errors":[],"uncaught_exceptions":[{{"source":"src/A.tsx#A","message":"TypeError: x is null","stack":"TypeError: x is null\n    at A (src/A.tsx:3:9)"}}],"failed_requests":[],"tauri_visible":false,"top_is_self":true,"a11y":"body\n  div","html":"<div></div>"}}"#
        )
    }

    #[test]
    fn a_report_is_accepted_only_for_its_run_and_its_schema() {
        let parsed = parse_probe_report(report("n1").as_bytes(), "n1").unwrap();
        assert!(!parsed.passed());
        let runtime = parsed.runtime_report();
        assert_eq!(runtime.uncaught_exception_count, 1);
        assert_eq!(runtime.inspected_url, "hilo-preview:src/A.tsx#A");
        assert!(runtime.dom_snapshot_hash.is_some());
        let items = parsed.diagnostics();
        assert_eq!(items[0].file_path, "src/A.tsx");
        assert!(items[0].message.contains("at A (src/A.tsx:3:9)"));

        assert_eq!(
            parse_probe_report(report("n1").as_bytes(), "n2"),
            Err(ProbeError::WrongNonce)
        );
        assert_eq!(
            parse_probe_report(report("").as_bytes(), ""),
            Err(ProbeError::WrongNonce)
        );
        let extra = report("n1").replacen("\"schema\":1", "\"schema\":1,\"trusted\":true", 1);
        assert!(matches!(
            parse_probe_report(extra.as_bytes(), "n1"),
            Err(ProbeError::Malformed(_))
        ));
        let schema = report("n1").replacen("\"schema\":1", "\"schema\":2", 1);
        assert_eq!(
            parse_probe_report(schema.as_bytes(), "n1"),
            Err(ProbeError::WrongSchema(2))
        );
        let huge = report("n1").replacen("<div></div>", &"x".repeat(MAX_HTML + 1), 1);
        assert_eq!(
            parse_probe_report(huge.as_bytes(), "n1"),
            Err(ProbeError::OutOfBounds)
        );
        assert_eq!(
            parse_probe_report(&vec![b' '; MAX_REPORT_BYTES + 1], "n1"),
            Err(ProbeError::TooLarge)
        );
    }

    #[test]
    fn a_visible_bridge_or_a_framing_parent_fails_the_preview() {
        let visible = report("n").replacen("\"tauri_visible\":false", "\"tauri_visible\":true", 1);
        let parsed = parse_probe_report(visible.as_bytes(), "n").unwrap();
        assert!(parsed.isolation_breached() && parsed.runtime_report().crashed);
        let framed = report("n").replacen("\"top_is_self\":true", "\"top_is_self\":false", 1);
        assert!(parse_probe_report(framed.as_bytes(), "n")
            .unwrap()
            .isolation_breached());
    }

    #[test]
    fn the_harness_embeds_paths_as_data_and_only_components_are_previewed() {
        let files = preview_harness(&["src/a\"); evil(\".tsx".into()], "n\"x");
        let harness = &files[1].1;
        assert!(harness.contains(r#"[["../src/a\"); evil(\".tsx","src/a\"); evil(\".tsx"]]"#));
        assert!(harness.contains(r#"const NONCE = "n\"x";"#));
        assert!(!harness.contains("__HILO_"));
        assert!(is_component_file("src/Badge.tsx") && is_component_file("ui/a.jsx"));
        assert!(!is_component_file("src/Badge.test.tsx") && !is_component_file("src/a.ts"));
        let document = snapshot_document("<p>hi</p>");
        assert!(document.contains("default-src 'none'") && document.contains("<p>hi</p>"));
    }
}
